# -*- coding: utf-8 -*-
"""
وكيل تصنيف الإيميلات — ورشة "كيف تبني Agent"
يقرأ مجموعة إيميلات، ويقرّر لكل واحد: مهم؟ ولا لا؟ مع السبب.

التشغيل:
    export ANTHROPIC_API_KEY=مفتاحك
    python agent.py
"""

import anthropic

# ============================================================
# الجزء ١: الاتصال بالموديل
# (هذا "الأنبوب" اللي يوصلنا بعقل الوكيل)
# ============================================================
client = anthropic.Anthropic()  # يقرأ المفتاح من البيئة تلقائياً
MODEL = "claude-haiku-4-5"       # موديل سريع ورخيص — مناسب للمهمة


# ============================================================
# الجزء ٢: التعليمات (البرومبت) — "شخصية" الوكيل وعقله
# هنا يتحدد كل سلوكه. غيّر هذا النص، يتغير الوكيل كلّه.
# ============================================================
SYSTEM = """انت مساعد ذكي مهمتك تصنيف الإيميلات لشخص مشغول.

لكل إيميل، قرّر: هل هو "مهم" أو "غير مهم"؟
- مهم: يحتاج رد أو إجراء أو فيه موعد أو معلومة حساسة (عمل، اجتماعات، مواعيد، أمور شخصية عاجلة).
- غير مهم: إعلانات، عروض تسويقية، نشرات بريدية، إشعارات تلقائية ما تحتاج تصرّف.

أجب بصيغة JSON فقط بدون أي نص إضافي وبدون علامات Markdown، بهذا الشكل:
{"classification": "مهم" أو "غير مهم", "reason": "سبب قصير بالعربية في جملة وحدة"}"""


# ============================================================
# الجزء ٣: البيانات — إيميلات جاهزة للتجربة
# (في تطبيق حقيقي، هذي تجي من Gmail عبر ربط الحساب)
# ============================================================
EMAILS = [
    {"from": "مدير المشروع", "subject": "اجتماع غداً الساعة ٩",
     "body": "نبغى نراجع خطة الربع القادم، حضورك ضروري ومعك التقرير."},
    {"from": "متجر تخفيضات", "subject": "🔥 خصم ٥٠٪ على كل شي!",
     "body": "عروض الويكند بدأت! اشترِ الحين قبل لا تنتهي الكمية."},
    {"from": "الموارد البشرية", "subject": "تحديث بيانات التأمين",
     "body": "نحتاج توقيعك على نموذج التأمين قبل نهاية الأسبوع، مرفق الرابط."},
    {"from": "نشرة تقنية", "subject": "أهم ٥ أخبار هذا الأسبوع",
     "body": "تابع آخر أخبار الذكاء الاصطناعي في نشرتنا الأسبوعية."},
    {"from": "البنك", "subject": "تنبيه: عملية شراء غير معتادة",
     "body": "رصدنا عملية بمبلغ كبير على بطاقتك. إذا ما كانت أنت، تواصل معنا فوراً."},
]


# ============================================================
# الجزء ٤: حلقة الوكيل — يمر على كل إيميل ويتصرّف
# ============================================================
import json


def classify_email(email):
    """يرسل إيميلاً واحداً للموديل ويرجّع قراره."""
    content = f"من: {email['from']}\nالموضوع: {email['subject']}\nالنص: {email['body']}"
    response = client.messages.create(
        model=MODEL,
        max_tokens=200,
        system=SYSTEM,
        messages=[{"role": "user", "content": content}],
    )
    raw = response.content[0].text.strip().replace("```json", "").replace("```", "")
    return json.loads(raw)


def main():
    print("\n📬 وكيل تصنيف الإيميلات بدأ العمل...\n")
    important = 0
    for i, email in enumerate(EMAILS, 1):
        result = classify_email(email)
        label = result["classification"]
        icon = "🔴" if label == "مهم" else "⚪️"
        if label == "مهم":
            important += 1
        print(f"{icon} [{label}] {email['subject']}")
        print(f"    └─ السبب: {result['reason']}\n")

    print(f"✅ خلص! صنّفت {len(EMAILS)} إيميلات، منها {important} مهمة تحتاج انتباهك.\n")


if __name__ == "__main__":
    main()
